export function bigrams(s: string): string[] {
  const r: string[] = [];
  for (let i = 0; i < s.length - 1; i++) {
    r.push(s.slice(i, i + 2));
  }
  return r;
}

export function dice(a: string, b: string): number {
  const x = bigrams(a);
  const y = bigrams(b);
  if (!x.length || !y.length) return 0;
  let hit = 0;
  const used: Record<number, boolean> = {};
  x.forEach((g) => {
    for (let i = 0; i < y.length; i++) {
      if (!used[i] && y[i] === g) {
        used[i] = true;
        hit++;
        break;
      }
    }
  });
  return (2 * hit) / (x.length + y.length);
}

export function charOverlap(a: string, b: string): number {
  const seen: Record<string, boolean> = {};
  for (let i = 0; i < b.length; i++) seen[b[i]] = true;
  let n = 0;
  const uniq: Record<string, boolean> = {};
  for (let i = 0; i < a.length; i++) {
    if (seen[a[i]] && !uniq[a[i]]) {
      uniq[a[i]] = true;
      n++;
    }
  }
  return n / Math.max(a.length, b.length);
}

export function findEmotion(text: string): string | null {
  const t = text.replace(/\s+/g, '');
  if (!t) return null;

  for (const k of Object.keys(RULE_BASED_DATA)) {
    for (const a of RULE_BASED_DATA[k].alias) {
      if (a === t) return k;
    }
  }

  for (const k of Object.keys(RULE_BASED_DATA)) {
    for (const a of RULE_BASED_DATA[k].alias) {
      if (t.includes(a) || (t.length >= 2 && a.includes(t))) return k;
    }
  }

  let best: string | null = null;
  let score = 0;
  for (const k of Object.keys(RULE_BASED_DATA)) {
    for (const a of RULE_BASED_DATA[k].alias) {
      const d = dice(t, a);
      if (d > score) {
        score = d;
        best = k;
      }
    }
  }
  return score >= 0.5 ? best : null;
}

export function suggestEmotions(text: string): string[] {
  const t = text.replace(/\s+/g, '');
  const rows = Object.keys(RULE_BASED_DATA)
    .map((k) => {
      let s = 0;
      RULE_BASED_DATA[k].alias.forEach((a) => {
        s = Math.max(s, dice(t, a) + 0.5 * charOverlap(t, a));
      });
      return { k, s };
    })
    .filter((r) => r.s > 0.2);

  rows.sort((a, b) => b.s - a.s);
  return rows.slice(0, 3).map((r) => r.k);
}

export function detectSlang(text: string): SlangEntry[] {
  const hits: SlangEntry[] = [];
  COMMON_SLANG.forEach((s) => {
    if (s.keys.some((k) => text.includes(k))) {
      hits.push(s);
    }
  });
  return hits;
}

export function getBookHue(str: string): number {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) % 360;
  }
  return h;
}
